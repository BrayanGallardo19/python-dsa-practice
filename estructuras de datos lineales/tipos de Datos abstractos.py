"""un tipo de dato abstracto (ADT) es una representación conceptual de un tipo de datos, incluyendo que operaciones se pueden realizar sobre el tipo de datos y las propiedades que tiene 


Los tipos abstractos de datos son como planos que describen que acciones se pueden realizar sobre un tipo de dato y como se comporta, pero no especifica como se realizan"""

"""un map es un ADT que gestiona colecciones de pares clave valor y sus operaciones de una manera especifica y eficiente"""

"""en un mapa cada valor está asociado a una clave especifica y unica lo que permite acceder a los valores de manera mas eficiente y rapida"""

""""El tipo abstracto de datos map también define operaciones importantes, como insertar pares clave-valor, obtener el valor asociado a una clave, actualizar el valor asociado a una clave, eliminar un par clave-valor y verificar si una clave existe en el map."""

"""en realidad no especifica como deben realizarse estas operaciones, solo define que operaciones deben estar disponibles y como deben comportarse"""

"""un hash map o tabla hash es una estructura concreta del tipo de datos map y estos realizan una tecnica llamada hashing para realizar operaciones comunes de manera eficiente"""

"""el hashing es un proceso que toma una clave y la transforma en un indice de una tabla, lo que permite acceder a los valores asociados a las claves de manera rapida y eficiente"""